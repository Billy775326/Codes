import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { delimiter, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const [major, minor] = process.versions.node.split('.').map(Number);
if (major !== 24 || minor < 19) {
  console.error('Install with Node.js 24.19 or newer in the 24.x line.');
  process.exitCode = 1;
} else {
  const directory = resolve(process.env.CODES_BIN_DIR ?? join(homedir(), '.local/bin'));
  const command = join(directory, 'codes');
  const launcher = fileURLToPath(new URL('../bin/codes.mjs', import.meta.url));
  const quote = (value) => "'" + value.replaceAll("'", "'\\''") + "'";
  const wrapper = `#!/bin/sh\n# Generated by codes install:command.\nexec ${quote(process.execPath)} ${quote(launcher)} "$@"\n`;
  mkdirSync(directory, { recursive: true });
  try {
    writeFileSync(command, wrapper, { flag: 'wx', mode: 0o755 });
  } catch (error) {
    if (error.code !== 'EEXIST') throw error;
    if (readFileSync(command, 'utf8') !== wrapper) {
      console.error(`Refusing to replace the existing command: ${command}`);
      console.error('Inspect it first, or choose another directory with CODES_BIN_DIR.');
      process.exitCode = 1;
    }
  }
  if (!process.exitCode) {
    console.log(`Installed ${command}. Run codes to start, or codes --help for usage.`);
    if (!(process.env.PATH ?? '').split(delimiter).includes(directory))
      console.log(`Add this directory to your shell PATH: export PATH=${quote(directory)}:"$PATH"`);
  }
}
